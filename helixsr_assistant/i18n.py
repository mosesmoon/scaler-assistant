"""User-interface translations for HelixSR 助手 (HelixSR Assistant).

``tr(key, **values)`` looks the key up in the current language and falls back
to English. Strings are ``str.format`` templates.
"""

from __future__ import annotations

import locale
import os
from typing import Optional

# (code, native name, Qt translation suffix)
LANGUAGES: list[tuple[str, str, str]] = [
    ("zh_TW", "台灣正體中文", "zh_TW"),
    ("zh_CN", "简体中文", "zh_CN"),
    ("en", "English", "en"),
    ("ja", "日本語", "ja"),
    ("de", "Deutsch", "de"),
    ("fr", "Français", "fr"),
    ("es", "Español", "es"),
    ("it", "Italiano", "it"),
    ("th", "ไทย", "th"),
    ("vi", "Tiếng Việt", "vi"),
    ("ms", "Bahasa Melayu", "ms"),
    ("hi", "हिन्दी", "hi"),
]
CODES = [code for code, _, _ in LANGUAGES]

# UI language -> Steam's language key in appinfo ``common/name_localized``.
# Steam has no Malay or Hindi store names, so those show the original name.
STEAM_LANGUAGES: dict[str, tuple[str, ...]] = {
    "zh_TW": ("tchinese",),
    "zh_CN": ("schinese",),
    "en": ("english",),
    "ja": ("japanese",),
    "de": ("german",),
    "fr": ("french",),
    "es": ("spanish", "latam"),
    "it": ("italian",),
    "th": ("thai",),
    "vi": ("vietnamese",),
    "ms": (),
    "hi": (),
}
DEFAULT = "en"

_current = DEFAULT


def system_language() -> str:
    raw = ""
    for key in ("LC_ALL", "LC_MESSAGES", "LANG", "LANGUAGE"):
        raw = os.environ.get(key, "")
        if raw:
            break
    if not raw:
        try:
            raw = locale.getlocale()[0] or ""
        except ValueError:
            raw = ""
    return match_language(raw)


def match_language(raw: str) -> str:
    tag = raw.split(":")[0].split(".")[0].replace("-", "_")
    lower = tag.lower()
    if lower.startswith("zh"):
        if any(part in lower for part in ("tw", "hk", "mo", "hant")):
            return "zh_TW"
        return "zh_CN"
    base = lower.split("_")[0]
    return base if base in CODES else DEFAULT


def set_language(code: Optional[str]) -> str:
    global _current
    _current = code if code in CODES else system_language()
    return _current


def current() -> str:
    return _current


def qt_suffix(code: Optional[str] = None) -> str:
    code = code or _current
    return next(suffix for c, _, suffix in LANGUAGES if c == code)


def localized_name(name: str, names: dict[str, str], code: Optional[str] = None) -> str:
    """The game's Steam store name in the UI language, else its original name."""
    for key in STEAM_LANGUAGES.get(code or _current, ()):
        if names.get(key):
            return names[key]
    return name


def tr(key: str, **values) -> str:
    text = STRINGS.get(_current, {}).get(key)
    if text is None:
        text = STRINGS[DEFAULT].get(key, key)
    return text.format(**values) if values else text


